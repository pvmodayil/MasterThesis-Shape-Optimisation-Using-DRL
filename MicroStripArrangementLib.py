def filterVectors(hw_micrstr: float, hw_arra: float, g: np.ndarray, x: np.ndarray) -> Tuple[np.ndarray,np.ndarray]:
    """
    Takes out only the required values from the x and g vectors
    Parameters
    ----------
    hw_micrstr : float
        half width of the microstrip
    hw_arra : float
        half width of the arrangement
    g : np.ndarray
        support points y-axis from the agent
    x : np.ndarray
        support points x-axis

    Returns
    -------
    Tuple[np.ndarray]
        filtered x and g vectors
    """
    logger.info(f"Input x-axis and g-points vectors are being filtred. Input shapes: x={x.shape}, g={g.shape}")
    filterMask = (x > hw_micrstr) & (x < hw_arra)
    
    filteredX = x[filterMask]
    filteredG = g[filterMask]
    
    return filteredG, filteredX

def calculatePotentialCoeffs(V0: float, hw_micrstr: float, hw_arra: float, num_fs: int, g: np.ndarray, x: np.ndarray) -> np.ndarray:
    """
    Function to calaculate the potential coefficients parallelly
    This function taken in g values for corresponding x valueswhich are from (hw_micrstr + delta to hw_arra - delta)
    
    Input
    -----------
    V0: potential of the microstrip
        float
    hw_micrstr: halw width of the microstrip
        float
    hw_arra: half width of the arrangement
        float
    num_fs(N): number of fourier coefficients
        float
    g: support points y-axis from agent
        numpy array
    x: support points x-axis hw_micrstr < x < hw_arra
        numpy array
    
    Output
    -----------
    vn = potential coefficients  
        np.ndarray      
    """
    # dimensionality check
    if np.size(x) != np.size(g):
        raise Exception(f'Dimensions of x-axis vector and g-points vector do not match! \n size x:{np.size(x)}, size g:{np.size(g)}')
    
    # check for positional values, should contain values only for hw_micrstr < x-axis vector < hw_arra
    if x[0] == 0 or x[0] == hw_micrstr or x[-1] == hw_arra:
        # filter the vectors to keep between the required range
        g, x = filterVectors(hw_micrstr, hw_arra, g, x)
    
    n = np.arange(num_fs) # create a vector with fourier coefficients
    m = np.size(x) # size of the input vectors
  
    # check if input vector is sorted
    if not np.all(np.diff(x) > 0):
        logger.error("Input x-axis values are not sorted. Sorting......")
        x = np.sort(x)
        # Sort g accordingly
        g = g[np.argsort(x)]
    
    if m == 1: #Only one spline knot
        raise Exception('Not enough spline knots. Make sure there are at least 2 between half width of microstrip and half width of arrangement!')
    
    # for the formula to work exactly as written it requires at least 3 spline nots between hw_micrstr and hw_arra
    if m == 2: # with just 2 spline knots the formula is adjusted
        outer_coeff = 2/hw_arra*V0*(1/((2*n+1)*np.pi/(2*hw_arra))**2)

        v_n1 = (g[0]-V0)/(x[0]-hw_micrstr)*(np.cos((2*n+1)*x[0]*np.pi/(2*hw_arra))-np.cos((2*n+1)*hw_micrstr*np.pi/(2*hw_arra)))
        v_n3 = g[1]/(hw_arra-x[1])*np.cos((2*n+1)*x[1]*np.pi/(2*hw_arra))

        cos1 = np.cos(x[1]*np.pi/(2*hw_arra)*(2*n+1)) # 1xN
        cos2 = np.cos(x[0]*np.pi/(2*hw_arra)*(2*n+1)) # 1xN
        v_n2 = (g[1]-g[0])/(x[1]-x[0])*(cos1-cos2) # 1xN 
        v_n = outer_coeff*(v_n1+v_n2+v_n3)

        return v_n
    
    # for cases with more than 2 spline knots
    outer_coeff = 2/hw_arra*V0*(1/((2*n+1)*np.pi/(2*hw_arra))**2)
    v_n1 = (g[0]-V0)/(x[0]-hw_micrstr)*(np.cos((2*n+1)*x[0]*np.pi/(2*hw_arra))-np.cos((2*n+1)*hw_micrstr*np.pi/(2*hw_arra))) # 1xN
    v_n3 = g[-1]/(hw_arra-x[-1])*np.cos((2*n+1)*x[m-1]*np.pi/(2*hw_arra)) # 1xN

    x_t = np.reshape(x,(-1,1)) # convert 1 x m vector into a m x 1 vector (Transpose)

    cos1 = np.cos(x_t[1:m]*np.pi/(2*hw_arra)*(2*n+1)) # m-1x1 * 1xN = m-1xN
    cos2 = np.cos(x_t[0:m-1]*np.pi/(2*hw_arra)*(2*n+1))
    fac1 = (g[1:m]-g[0:m-1])/(x[1:m]-x[0:m-1]) # 1xm-1
    v_n2 = np.matmul(fac1,(cos1-cos2)) # 1xm-1 * m-1xN = 1xN

    v_n = outer_coeff*(v_n1+v_n2+v_n3) # 1xN

    return v_n

def calculatePotential(hw_arra: float, num_fs: int, vn:np.ndarray,x:np.ndarray) -> np.ndarray:
    """
    Function to calculate the potential

    Parameters
    ----------
    hw_arra : float
        half width of the arrangement
    num_fs : int
        number of fourier coefficients
    vn : np.ndarray
        potential coefficients
    x : np.ndarray
        support points x-axis

    Returns
    -------
    VF : np.ndarray
        potential
    """
    n = np.arange(num_fs)[:, np.newaxis] # create a vector with fourier coefficients Nx1
    
    cos1 = np.cos((2*n+1)*(np.pi/(2*hw_arra))*x) # Nxm
    VF = np.matmul(vn,cos1)
    
    return VF
    
