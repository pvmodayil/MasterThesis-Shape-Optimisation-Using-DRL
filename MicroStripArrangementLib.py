# define logarithmic implementations for cosh and sinh to improve numerical stability
# sinh = (e^x - e^(-x))/2 => ln(sinh(x)) = ln(e^x - e^(-x)) - ln(2)
# cosh = (e^x + e^(-x))/2 => ln(cosh(x)) = ln(e^x + e^(-x)) - ln(2)
# logsumexp computes ln(e^x - e^(-x)) => max(x, -x) + ln(e^(x - max(x, -x)) + e^(-x - max(x, -x)))
# this ensures numerical stability as it reduces the values being calculated within exponential terms
######################################################################################
def logsinh(vector:np.ndarray) -> np.ndarray:
    """
    Auxiliary function
    Computes the natural logarithm of the sinh function, bypassing overflows that would happen if the sinh would be directly computed.
    """
    ones = np.ones_like(vector) # weight: equally weighted summation
    return logsumexp([vector, -vector], b=[ones, -ones], axis=0) - np.log(2) 

def logcosh(vector:np.ndarray) -> np.ndarray:
    """
    Auxiliary function
    Computes the natural logarithm of the cosh function, bypassing overflows that would happen if the cosh would be directly computed.
    """
    ones=np.ones_like(vector)
    return logsumexp([vector, -vector], b=[ones, ones], axis=0) - np.log(2) #If you encounter an overflow error here, you messed up big time. Please try another implementation or write your own.

def calculateEnergy(er1: float, er2: float, hw_arra: float, ht_arra: float, ht_subs: float, num_fs: int, vn: np.ndarray) -> float:
    """
    Function to calaculate the total energy of the arrangement
    
    Input
    -----------
    er1: permitivitty of medium 1
        float
    er2: permitivitty of medium 2
        float
    hw_arra: half width of the arrangement
        float
    ht_arra: height of the arrangement
        float
    ht_subs: height of the substrate
        float
    num_fs: number of fourier coefficients
        int
    vn: array of potential coefficients
        numpy array
    
    Output
    -----------
    W12 = total energy of the arrangement  
        float     
    """
    e1 = er1*8.854E-12 # 8.54E-12 is permittivity constant e0
    e2 = er2*8.854E-12 
    
    # following the formula
    ###########################################################################################
    n = np.arange(num_fs) # create a vector with fourier coefficients
    
    coeff = (2*n+1)*np.pi*vn**2 # 1 x N
    # w1
    ###########################################################################################
    logcosh1 = logcosh((2*n+1)*np.pi*(ht_arra-ht_subs)/(2*hw_arra)) # 1 x N
    logsinh1 = logsinh((2*n+1)*np.pi*(ht_arra-ht_subs)/(2*hw_arra)) # 1 x N

    coth1 = np.exp(logcosh1-logsinh1) # log(cosh/sinh) = log(cosh) - log(sinh)
    w1 = e1/4*np.sum(coeff*coth1)

    # w2
    ###########################################################################################
    logcosh2 = logcosh((2*n+1)*np.pi*ht_subs/(2*hw_arra)) # 1 x N
    logsinh2 = logsinh((2*n+1)*np.pi*ht_subs/(2*hw_arra)) # 1 x N

    coth2 = np.exp(logcosh2-logsinh2)
    w2 = e2/4*np.sum(coeff*coth2)

    W12 = w1+w2
    
    
    return W12

