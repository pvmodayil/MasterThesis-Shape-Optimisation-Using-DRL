def calculateChargeDensityCoeffs(er1: float, er2: float, hw_arra: float, ht_arra: float, ht_subs: float, num_fs: int, vn: np.ndarray) -> np.ndarray:
    """
    calculates the charge density coefficients sigma_n
    
    Input
    -----------
    er1: permitivitty of medium 1
        float
    er2: permitivitty of medium 2
        float
    hw_arra: half width of the arrangement
        float
    ht_arra: height of the arrangement
        float
    ht_subs: height of the substrate
        float
    num_fs: number of fourier coefficients
        int
    vn: array of potential coefficients
        numpy array
    
    Output
    -----------
    sigma_n = charge density coefficients
        float     
    """
    e1 = er1*8.854E-12 # 8.54E-12 is permittivity constant e0
    e2 = er2*8.854E-12 
    
    # following the formula
    ###########################################################################################
    n = np.arange(num_fs) # create a vector with fourier coefficients
    
    outer_coeff = vn*(2*n+1)*np.pi/(2*hw_arra)
    
    logcosh2 = logcosh((2*n+1)*np.pi*(ht_subs)/(2*hw_arra)) # 1 x N
    logsinh2 = logsinh((2*n+1)*np.pi*(ht_subs)/(2*hw_arra)) # 1 x N
    coth2 = np.exp(logcosh2 - logsinh2)
    
    logcosh1 = logcosh((2*n+1)*np.pi*(ht_arra-ht_subs)/(2*hw_arra)) # 1 x N
    logsinh1 = logsinh((2*n+1)*np.pi*(ht_arra-ht_subs)/(2*hw_arra)) # 1 x N
    coth1 = np.exp(logcosh1 - logsinh1)
    
    sigma_n = outer_coeff*(e2*coth2 + e1*coth1)
    
    return sigma_n

def calculateChargeDensity(er1: float, er2: float, ht_arra: float, ht_subs: float, hw_arra: float, num_fs: int, vn:np.ndarray,x:np.ndarray) -> np.ndarray:
    """
    ccalculates surface charge density

    Parameters
    ----------
    er1: permitivitty of medium 1
        float
    er2: permitivitty of medium 2
        float
    ht_arra: height of the arrangement
        float
    ht_subs: height of the substrate
        float
    hw_arra : float
        half width of the arrangement
    num_fs : int
        number of fourier coefficients
    vn : np.ndarray
        potential coefficients
    x : np.ndarray
        support points x-axis

    Returns
    -------
    Sigma : np.ndarray
        surface charge density
    """
    sigma_n = calculateChargeDensityCoeffs(er1, er2, hw_arra, ht_arra, ht_subs, num_fs, vn)
    n = np.arange(num_fs)[:, np.newaxis] # create a vector with fourier coefficients Nx1
    
    cos1 = np.cos((2*n+1)*(np.pi/(2*hw_arra))*x) # Nxm
    Sigma = np.matmul(sigma_n,cos1)
    
    return Sigma